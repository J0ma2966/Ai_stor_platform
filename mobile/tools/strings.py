def android_escape(s):
    s = escape(s)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "ui/src/main/res")

def write():
    names = [n for n, _, _ in S]
    dup = {n for n in names if names.count(n) > 1}
    assert not dup, f"duplicate keys: {dup}"
    for folder, idx in (("values", 1), ("values-uz", 2)):
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               "<!-- Сгенерировано mobile/tools/strings.py — правьте таблицу там. -->", "<resources>"]
        for row in S:
            fmt = ' formatted="false"' if "%" in row[idx] and "%1$" not in row[idx] else ""
            out.append(f'    <string name="{row[0]}"{fmt}>{android_escape(row[idx])}</string>')
        out.append("</resources>\n")
        with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as f:
            f.write("\n".join(out))

def check():
    names = {n for n, _, _ in S}
    used = set()
    for base, _, files in os.walk(ROOT):
        if "/build" in base or "/core" in base:
            continue
        for fn in files:
            if fn.endswith(".kt"):
                used |= set(re.findall(r"R\.string\.(\w+)", open(os.path.join(base, fn), encoding="utf-8").read()))
    missing = sorted(used - names)
    unused = sorted(names - used)
    # параметры формата должны совпадать в ru и uz
    bad = [n for n, ru, uz in S if sorted(re.findall(r"%\d\$[sd]", ru)) != sorted(re.findall(r"%\d\$[sd]", uz))]
    print("missing:", missing)
    print("unused:", unused)
    print("format mismatch:", bad)
    return 1 if missing or bad else 0

if __name__ == "__main__":
    write()
    if "--check" in sys.argv:
        sys.exit(check())
